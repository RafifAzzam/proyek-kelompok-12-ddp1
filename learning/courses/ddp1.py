def _build_ddp1_course():
    topics = []
    for raw_topic in RAW_TOPICS:
        lessons = []
        for raw_lesson in raw_topic["lessons"]:
            lesson_id = raw_lesson["id"]
            lesson_detail_data = RAW_LESSONS.get(lesson_id, {})

            raw_steps = lesson_detail_data.get("steps", [])
            steps = []
            for s in raw_steps:
                steps.append(
                    Step(
                        id=s["id"],
                        type=s["type"],
                        badge=s.get("badge", ""),
                        title=s.get("title"),
                        content_blocks=s.get("content_blocks"),
                        question=s.get("question"),
                        choices=s.get("choices"),
                        answer=s.get("answer"),
                        explanation=s.get("explanation"),
                    )
                )

            lesson_obj = Lesson(
                id=lesson_id,
                title=raw_lesson["title"],
                duration=raw_lesson["duration"],
                summary=raw_lesson["summary"],
                xp_reward=lesson_detail_data.get("xp_reward", 50),
                is_locked=raw_lesson.get("is_locked", True),
                steps=steps,
                topic_id=raw_topic["id"],
                topic_title=raw_topic["title"],
                course_id="ddp1",
            )
            lessons.append(lesson_obj)

        topics.append(
            Topic(
                id=raw_topic["id"],
                title=raw_topic["title"],
                description=raw_topic["description"],
                badge=raw_topic["badge"],
                lessons=lessons,
            )
        )

    return Course(
        id="ddp1",
        name="Dasar-Dasar Pemrograman 1",
        code="CSGE601020",
        icon="🐍",
        description="Pelajari pondasi dasar algoritma dan pemrograman menggunakan bahasa Python.",
        topics=topics,
    )


course_ddp1 = _build_ddp1_course()

